// Where application documents are stored. See docs/documents.md.
//
// Production: a private Cloudflare R2 bucket, reached over its S3 API. Nothing
// in it is public; a download is a presigned URL that expires in minutes.
// Development: a folder on disk (./.uploads), so no Cloudflare account is
// needed. A production deploy with no R2 configured refuses to store anything
// rather than writing to a serverless function's throwaway disk.

import { AwsClient } from "aws4fetch";
import { mkdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";

export interface Storage {
  put(key: string, bytes: Uint8Array<ArrayBuffer>, contentType: string): Promise<void>;
  /** A response that delivers the object to the browser. */
  serve(key: string, headers: Headers): Promise<Response>;
}

const DOWNLOAD_URL_TTL_SECONDS = 300;

function r2(): Storage {
  const { R2_ACCOUNT_ID, R2_ACCESS_KEY_ID, R2_SECRET_ACCESS_KEY, R2_BUCKET } = process.env;
  if (!R2_ACCOUNT_ID || !R2_ACCESS_KEY_ID || !R2_SECRET_ACCESS_KEY || !R2_BUCKET) {
    throw new Error("R2 is partly configured; set all four R2_* variables (see .env.example)");
  }
  const client = new AwsClient({
    accessKeyId: R2_ACCESS_KEY_ID,
    secretAccessKey: R2_SECRET_ACCESS_KEY,
    service: "s3",
    region: "auto",
  });
  const objectUrl = (key: string) =>
    `https://${R2_ACCOUNT_ID}.r2.cloudflarestorage.com/${R2_BUCKET}/${key.split("/").map(encodeURIComponent).join("/")}`;

  return {
    async put(key, bytes, contentType) {
      const res = await client.fetch(objectUrl(key), {
        method: "PUT",
        body: bytes,
        headers: { "content-type": contentType },
      });
      if (!res.ok) throw new Error(`R2 upload failed: ${res.status}`);
    },

    async serve(key, headers) {
      // Presign a short-lived GET that carries our response headers, so R2
      // returns the file with the same disposition and type we would.
      const url = new URL(objectUrl(key));
      url.searchParams.set("X-Amz-Expires", String(DOWNLOAD_URL_TTL_SECONDS));
      url.searchParams.set("response-content-type", headers.get("content-type") ?? "application/octet-stream");
      const disposition = headers.get("content-disposition");
      if (disposition) url.searchParams.set("response-content-disposition", disposition);
      const signed = await client.sign(url.toString(), { method: "GET", aws: { signQuery: true } });
      return new Response(null, {
        status: 302,
        headers: { location: signed.url, "cache-control": "no-store" },
      });
    },
  };
}

function local(): Storage {
  const root = path.resolve(process.env.UPLOADS_DIR ?? ".uploads");
  // Keys are generated by the server, but resolve and check anyway: a path
  // that escapes the folder is a bug, never a file to read.
  const resolve = (key: string) => {
    const file = path.resolve(root, key);
    if (!file.startsWith(root + path.sep)) throw new Error("Invalid storage key");
    return file;
  };

  return {
    async put(key, bytes) {
      const file = resolve(key);
      await mkdir(path.dirname(file), { recursive: true });
      await writeFile(file, bytes);
    },

    async serve(key, headers) {
      try {
        return new Response(await readFile(resolve(key)), { headers });
      } catch {
        return new Response("Not found", { status: 404 });
      }
    },
  };
}

let _storage: Storage | null = null;

export function getStorage(): Storage {
  if (_storage) return _storage;
  if (process.env.R2_BUCKET) {
    _storage = r2();
  } else if (process.env.NODE_ENV === "production") {
    throw new Error("Document storage is not configured: set the R2_* variables");
  } else {
    _storage = local();
  }
  return _storage;
}
